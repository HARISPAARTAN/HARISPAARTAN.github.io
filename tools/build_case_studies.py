def pager_link(ctx: PageContext, from_dir: str, target: Neighbour | None, direction: str) -> str:
    ui, lang = ctx.ui, ctx.lang
    if target is None:
        href = root_prefix(from_dir) + "#work"
        small = tr(ui, "pager.home_" + ("prev" if direction == "prev" else "next"), lang)
        title = tr(ui, "pager.home_title", lang)
    else:
        href = rel_url(from_dir, page_dir(target.slug, lang))
        small = tr(ui, "pager." + direction, lang)
        title = target.title[lang]
    cls = ' class="next"' if direction == "next" else ""
    return f'<a{cls} href="{esc(href)}" rel="{direction}"><small>{esc(small)}</small><span>{esc(title)}</span></a>'


