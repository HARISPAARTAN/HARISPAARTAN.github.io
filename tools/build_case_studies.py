# ---------------------------------------------------------------- small text helpers

def fmt(value: float) -> str:
    """A coordinate with at most two decimals, no trailing zeros and no negative zero."""
    text = f"{round(float(value), 2):.2f}".rstrip("0").rstrip(".")
    return "0" if text in ("", "-0") else text


def clean(text: str) -> str:
    return " ".join(text.split())


def esc(text: str) -> str:
    return html.escape(text, quote=True)


_INLINE = re.compile(r"\[(?P<label>[^\[\]]+)\]\((?P<url>[^()\s]+)\)|\*\*(?P<bold>.+?)\*\*")
_LINK_OK = re.compile(r"^(https?://\S+|/(?!/)\S*|\./\S*|\.\./\S*|#\S+)$")


def inline(text: str) -> str:
    """Escape text and turn the two allowed markups, **bold** and [label](url), into tags."""
    out: list[str] = []
    pos = 0
    for m in _INLINE.finditer(text):
        out.append(esc(text[pos:m.start()]))
        if m.group("label") is not None:
            out.append(f'<a href="{esc(m.group("url"))}">{esc(m.group("label"))}</a>')
        else:
            out.append(f"<strong>{esc(m.group('bold'))}</strong>")
        pos = m.end()
    out.append(esc(text[pos:]))
    return "".join(out)


def plain(text: str) -> str:
    """The text without its markup (for meta tags and attributes)."""
    return _INLINE.sub(lambda m: m.group("label") if m.group("label") is not None else m.group("bold"), text)


def short_description(text: str, limit: int = 300) -> str:
    """The first sentences of a text that fit into a meta description."""
    sentences = re.split(r"(?<=[.!?])\s+", plain(text))
    out = sentences[0]
    for sentence in sentences[1:]:
        if len(out) + 1 + len(sentence) > limit:
            break
        out += " " + sentence
    return out


def text_width(text: str, style: tuple[str, float, float]) -> float:
    font, size, spacing = style
    return len(text) * (GLYPH_EM[font] + spacing) * size


PLURAL = {"node": "nodes", "edge": "edges", "entity": "entities", "step": "steps"}


def suggest(word: str, options) -> str:
    close = difflib.get_close_matches(word, list(options), n=1)
    return f' (did you mean "{close[0]}"?)' if close else ""


def item_path(base: str, index: int, ident: object = None) -> str:
    """flow.nodes[app] for an item with an id, flow.nodes[#3] (third table) otherwise."""
    return f"{base}[{ident}]" if isinstance(ident, str) and ident else f"{base}[#{index + 1}]"


# ---------------------------------------------------------------- typed access with readable errors

def check_unknown(r: Report, table: dict, path: str, allowed) -> None:
    for key in table:
        if key not in allowed:
            r.error(f"{path}.{key}" if path else key,
                    f'unknown key "{key}"{suggest(key, allowed)}; allowed keys here: {", ".join(sorted(allowed))}')


def get_table(r: Report, parent: dict, key: str, path: str, required: bool = True) -> dict | None:
    if key not in parent:
        if required:
            r.error(path, f"missing required table [{path}]")
        return None
    if not isinstance(parent[key], dict):
        r.error(path, "must be a table")
        return None
    return parent[key]


def get_list(r: Report, parent: dict, key: str, path: str, required: bool = True, minimum: int = 0,
             maximum: int | None = None, what: str = "items") -> list:
    if key not in parent:
        if required:
            r.error(path, f"missing required list ({what})")
        return []
    value = parent[key]
    if not isinstance(value, list):
        r.error(path, "must be a list")
        return []
    if len(value) < minimum:
        r.error(path, f"needs at least {minimum} {what}, found {len(value)}")
    if maximum is not None and len(value) > maximum:
        r.error(path, f"allows at most {maximum} {what}, found {len(value)}")
    return value


def get_str(r: Report, parent: dict, key: str, path: str, required: bool = True, regex: re.Pattern | None = None,
            regex_hint: str = "", choices=None) -> str | None:
    if key not in parent:
        if required:
            r.error(path, "missing required key")
        return None
    value = parent[key]
    if not isinstance(value, str):
        r.error(path, "must be a string")
        return None
    value = clean(value)
    if not value:
        r.error(path, "text is empty")
        return None
    if regex is not None and not regex.match(value):
        r.error(path, f'invalid value "{value}"{(": " + regex_hint) if regex_hint else ""}')
        return None
    if choices is not None and value not in choices:
        r.error(path, f'invalid value "{value}"; allowed: {", ".join(choices)}{suggest(value, choices)}')
        return None
    return value


def get_int(r: Report, parent: dict, key: str, path: str, minimum: int = 1) -> int | None:
    if key not in parent:
        r.error(path, "missing required key")
        return None
    value = parent[key]
    if isinstance(value, bool) or not isinstance(value, int):
        r.error(path, "must be a whole number")
        return None
    if value < minimum:
        r.error(path, f"must be at least {minimum}")
        return None
    return value


def pair_from(r: Report, value: object, path: str, plain_ok: bool = False) -> dict | None:
    """Validate a pair {en, de}. With plain_ok a plain string counts for both languages."""
    if isinstance(value, str) and plain_ok:
        text = clean(value)
        if not text:
            r.error(path, "text is empty")
            return None
        return {"en": text, "de": text}
    if not isinstance(value, dict):
        r.error(path, f'must be a pair of texts: write {path}.en = "..." and {path}.de = "..."')
        return None
    ok = True
    for key in value:
        if key not in LANGS:
            r.error(f"{path}.{key}", f'unknown language "{key}"; a text has only "en" and "de"')
            ok = False
    out: dict[str, str] = {}
    for lang in LANGS:
        if lang not in value:
            r.error(f"{path}.{lang}", f"missing {LANG_NAME[lang]} text (every text needs both en and de)")
            ok = False
            continue
        if not isinstance(value[lang], str):
            r.error(f"{path}.{lang}", "must be a string")
            ok = False
            continue
        text = clean(value[lang])
        if not text:
            r.error(f"{path}.{lang}", f"{LANG_NAME[lang]} text is empty")
            ok = False
            continue
        out[lang] = text
    return out if ok else None


def get_pair(r: Report, parent: dict, key: str, path: str, required: bool = True, plain_ok: bool = False,
             rich: bool = False, links: bool = True) -> dict | None:
    if key not in parent:
        if required:
            r.error(path, f'missing text: add {path}.en = "..." and {path}.de = "..."')
        return None
    pair = pair_from(r, parent[key], path, plain_ok)
    if pair and rich:
        check_rich(r, pair, path, links)
    return pair


def check_rich(r: Report, pair: dict, path: str, links: bool = True) -> None:
    """Links in running text may point to https/http addresses, site paths or anchors, nothing else.
    Where links=False (the step texts, which sit inside buttons) only **bold** is allowed."""
    for lang in LANGS:
        for m in _INLINE.finditer(pair[lang]):
            url = m.group("url")
            if url is None:
                continue
            if not links:
                r.error(f"{path}.{lang}", f'links are not allowed in this text because it sits inside a button; remove "[{m.group("label")}]({url})" (**bold** is fine)')
            elif not _LINK_OK.match(url):
                r.error(f"{path}.{lang}", f'link target "{url}" is not allowed; use https://..., a site path starting with /, or #anchor')


def check_fit(r: Report, path: str, pair: dict | None, style: tuple[str, float, float], avail: float, where: str,
              upper: bool = False) -> None:
    """Error when a text is estimated to be wider than the space its box leaves for it."""
    if not pair:
        return
    same = pair["en"] == pair["de"]
    for lang in LANGS:
        if same and lang == "de":
            continue
        text = pair[lang].upper() if upper else pair[lang]
        width = text_width(text, style)
        if width > avail + 1e-9:
            per_char = (GLYPH_EM[style[0]] + style[2]) * style[1]
            limit = max(1, int(avail // per_char))
            target = path if same else f"{path}.{lang}"
            r.error(target, f"text is about {math.ceil(width)} units wide ({len(text)} characters x {per_char:.2f}) but the box "
                            f"({where}) leaves {math.floor(avail)}; shorten it to about {limit} characters or make the box wider")


