def rel_url(from_dir: str, to_dir: str, fragment: str = "") -> str:
    rel = posixpath.relpath(to_dir, from_dir)
    return ("./" if rel == "." else rel + "/") + fragment


def root_prefix(from_dir: str) -> str:
    return "../" * (from_dir.count("/") + 1)


def format_date(ui: dict, lang: str, date: datetime.date) -> str:
    pattern = tr(ui, "date.format", lang)
    month = ui["date"]["months"][lang][date.month - 1]
    return pattern.replace("{d}", str(date.day)).replace("{month}", month).replace("{y}", str(date.year))


