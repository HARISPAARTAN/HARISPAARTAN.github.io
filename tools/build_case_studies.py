@dataclass
class Issue:
    file: str
    path: str
    message: str

    def __str__(self) -> str:
        return f"{self.file}: {self.path}: {self.message}" if self.path else f"{self.file}: {self.message}"


class Report:
    """Collects the problems found in one file so an author can fix them all in one go."""

    def __init__(self, label: str) -> None:
        self.label = label
        self.errors: list[Issue] = []
        self.warnings: list[Issue] = []

    def error(self, path: str, message: str) -> None:
        self.errors.append(Issue(self.label, path, message))

    def warn(self, path: str, message: str) -> None:
        self.warnings.append(Issue(self.label, path, message))


