def parse_anchor(r: Report, value: object, path: str, boxes: dict | None, what: str) -> Anchor | None:
    """node.side or node.side@0.3; the number is the position along the side from 0 (left/top) to 1 (right/bottom)."""
    if not isinstance(value, str):
        r.error(path, 'must be a string like "app.right" or "lists.bottom@0.3"')
        return None
    m = ANCHOR_RE.match(value.strip())
    if not m:
        r.error(path, f'bad anchor "{value}": write <{what} id>.<side> or <{what} id>.<side>@<0..1> with side one of '
                      f'top, right, bottom, left (for example "app.right" or "lists.bottom@0.3")')
        return None
    ident, side, t = m.group(1), m.group(2), m.group(3)
    position = float(t) if t is not None else 0.5
    if position > 1:
        r.error(path, f'anchor position @{t} must be between 0 and 1')
        return None
    if boxes is not None and ident not in boxes:
        r.error(path, f'unknown {what} "{ident}" in anchor "{value}"{suggest(ident, boxes)}; known {PLURAL[what]}: {", ".join(boxes) or "none"}')
        return None
    return Anchor(ident, side, position)


def anchor_xy(box: Box, side: str, t: float) -> tuple:
    if side == "top":
        return box.x + t * box.w, box.y
    if side == "bottom":
        return box.x + t * box.w, box.bottom
    if side == "left":
        return box.x, box.y + t * box.h
    return box.right, box.y + t * box.h


def _bezier(p0, c1, c2, p3, steps: int = 16) -> list:
    pts = []
    for i in range(steps + 1):
        t = i / steps
        u = 1 - t
        pts.append((u ** 3 * p0[0] + 3 * u * u * t * c1[0] + 3 * u * t * t * c2[0] + t ** 3 * p3[0],
                    u ** 3 * p0[1] + 3 * u * u * t * c1[1] + 3 * u * t * t * c2[1] + t ** 3 * p3[1]))
    return pts


def connect(start: tuple, n0: tuple, finish: tuple, n3: tuple, gap: float = 0.0, head: bool = False) -> Link:
    """Connector from an anchor (outward side normal n0) to another anchor (outward side normal n3).

    A straight line when the two anchors line up (facing sides, same position across); otherwise a cubic curve whose
    control points lead out of the sides along their normals. With head=True the line stops where the arrowhead
    starts and the arrowhead (a small triangle) ends ARROW_GAP before the target side.
    """
    tip = (finish[0] + n3[0] * gap, finish[1] + n3[1] * gap)
    end = (tip[0] + n3[0] * HEAD_LEN, tip[1] + n3[1] * HEAD_LEN) if head else tip
    vx, vy = end[0] - start[0], end[1] - start[1]
    facing = n3 == (-n0[0], -n0[1])
    along = vx * n0[0] + vy * n0[1]
    across = abs(vx * n0[1] - vy * n0[0])
    if facing and along > 0 and across <= STRAIGHT_TOL:
        d = f"M{fmt(start[0])},{fmt(start[1])} L{fmt(end[0])},{fmt(end[1])}"
        points = [(start[0] + (end[0] - start[0]) * i / 16, start[1] + (end[1] - start[1]) * i / 16) for i in range(17)]
    else:
        def axis(n: tuple) -> float:
            return abs(vx) if n[0] else abs(vy)
        if facing and along > 0:      # an S-curve between facing sides: bend over half the distance, never overshoot
            k0 = k1 = max(4.0, along / 2)
        else:                         # corners and U-turns need room to leave the side
            floor = 40 if n0 == n3 else 12
            k0, k1 = max(floor, axis(n0) / 2), max(floor, axis(n3) / 2)
        c1 = (start[0] + n0[0] * k0, start[1] + n0[1] * k0)
        c2 = (end[0] + n3[0] * k1, end[1] + n3[1] * k1)
        d = (f"M{fmt(start[0])},{fmt(start[1])} C{fmt(c1[0])},{fmt(c1[1])} {fmt(c2[0])},{fmt(c2[1])} "
             f"{fmt(end[0])},{fmt(end[1])}")
        points = _bezier(start, c1, c2, end)
    head_d = ""
    if head:
        px, py = -n3[1], n3[0]
        head_d = (f"M{fmt(tip[0])},{fmt(tip[1])} L{fmt(end[0] + px * HEAD_HALF)},{fmt(end[1] + py * HEAD_HALF)} "
                  f"L{fmt(end[0] - px * HEAD_HALF)},{fmt(end[1] - py * HEAD_HALF)}z")
        points = points + [tip]
    return Link(d, head_d, start, n0, finish, n3, points)


def boxes_problems(r: Report, boxes: dict, width: int, path_of, label: str) -> None:
    """Boxes must lie inside the viewBox and keep CLEARANCE from each other."""
    ids = list(boxes)
    for ident in ids:
        b = boxes[ident]
        problems = []
        if b.x < 0:
            problems.append(f"x is {fmt(b.x)} (must be 0 or more)")
        if b.y < 0:
            problems.append(f"y is {fmt(b.y)} (must be 0 or more)")
        if b.right > width:
            problems.append(f"the box ends at x = {fmt(b.right)} but the viewBox is only {width} wide")
        if problems:
            r.error(path_of(ident), f"{label}: box lies outside its viewBox: " + "; ".join(problems))
    for i, a_id in enumerate(ids):
        for b_id in ids[i + 1:]:
            a, b = boxes[a_id], boxes[b_id]
            if (a.x < b.right + CLEARANCE and b.x < a.right + CLEARANCE
                    and a.y < b.bottom + CLEARANCE and b.y < a.bottom + CLEARANCE):
                r.error(path_of(b_id), f'{label}: box overlaps "{a_id}" or lies closer than {CLEARANCE} units to it '
                                       f'(this box x {fmt(b.x)}, y {fmt(b.y)}, {fmt(b.w)} x {fmt(b.h)}; "{a_id}" x {fmt(a.x)}, '
                                       f'y {fmt(a.y)}, {fmt(a.w)} x {fmt(a.h)})')


def outside_note(link: Link, width: int) -> str:
    """'it reaches x = 412 but the viewBox is 400 wide' when a connector leaves the canvas, else an empty string."""
    xs, ys = [px for px, _ in link.points], [py for _, py in link.points]
    notes = []
    if min(xs) < -0.01:
        notes.append(f"it reaches x = {fmt(min(xs))}, left of 0")
    if max(xs) > width + 0.01:
        notes.append(f"it reaches x = {fmt(max(xs))} but the viewBox is {width} wide")
    if min(ys) < -0.01:
        notes.append(f"it reaches y = {fmt(min(ys))}, above 0")
    return "; ".join(notes)


def warn_crossings(r: Report, path: str, label: str, link: Link, boxes: dict, joined: tuple) -> None:
    """Warn when a connector runs through a box it does not join (the picture would suggest a connection)."""
    for ident, b in boxes.items():
        if ident in joined:
            continue
        if any(b.x + 1 < px < b.right - 1 and b.y + 1 < py < b.bottom - 1 for px, py in link.points):
            r.warn(path, f'{label}: the line passes through "{ident}"; move a box or choose other anchors')


def triple(r: Report, parent: dict, key: str, path: str) -> tuple | None:
    if key not in parent:
        r.error(path, "missing required key: [x, y, width]")
        return None
    v = parent[key]
    if (not isinstance(v, list) or len(v) != 3
            or any(isinstance(n, bool) or not isinstance(n, (int, float)) or not math.isfinite(n) for n in v)):
        r.error(path, "must be a list of three numbers [x, y, width]")
        return None
    if v[2] <= 0:
        r.error(path, "width must be greater than 0")
        return None
    return float(v[0]), float(v[1]), float(v[2])


def pill_geometry(box: Box, text: str, pos: str) -> tuple:
    """x, y, width of a badge pill straddling the top edge of its box."""
    width = text_width(text, PILL_STYLE) + 20
    if pos == "left":
        x = box.x + 10
    elif pos == "center":
        x = box.x + (box.w - width) / 2
    else:
        x = box.right - width - 10
    return x, box.y - PILL_H / 2, width


def layout_flow(r: Report, nodes: list, edges: list, steps: list, which: str) -> FlowLayout | None:
    width = FLOW_WIDTH[which]
    label = f"{which} layout"
    boxes: dict[str, Box] = {}
    for n in nodes:
        x, y, w = getattr(n, which)
        boxes[n.id] = Box(n.id, x, y, w, NODE_H)
    boxes_problems(r, boxes, width, lambda i: f"flow.nodes[{i}].{which}", label)
    for n in nodes:
        w = boxes[n.id].w
        where = f"{label}, box {fmt(w)} wide"
        check_fit(r, f"flow.nodes[{n.id}].tag", n.tag, TAG_STYLE, w - 28, where, upper=True)
        check_fit(r, f"flow.nodes[{n.id}].title", n.title, TITLE_STYLE, w - 28, where)
        check_fit(r, f"flow.nodes[{n.id}].role", n.role, ROLE_STYLE, w - 28, where)
    links: dict[str, Link] = {}
    lowest = max([b.bottom for b in boxes.values()] or [0])
    for e in edges:
        a_from, a_to = getattr(e, which)
        link = connect(anchor_xy(boxes[a_from.node], a_from.side, a_from.t), SIDES[a_from.side],
                       anchor_xy(boxes[a_to.node], a_to.side, a_to.t), SIDES[a_to.side], gap=ARROW_GAP, head=True)
        links[e.id] = link
        outside = outside_note(link, width)
        if outside:
            r.error(f"flow.edges[{e.id}].{which}", f"{label}: the arrow leaves the viewBox ({outside}); move the anchors or the boxes, or use sides that leave more room")
        warn_crossings(r, f"flow.edges[{e.id}].{which}", label, link, boxes, (a_from.node, a_to.node))
        lowest = max(lowest, max(py for _, py in link.points))
    for s in steps:
        if s.badge and s.badge.node in boxes:
            box = boxes[s.badge.node]
            for lang in LANGS:
                x, y, w = pill_geometry(box, s.badge.text[lang], s.badge.pos)
                if x < 0 or x + w > width or y < 0:
                    r.error(f"flow.steps[{s.id}].badge", f"{label}: the badge pill (x {fmt(x)} to {fmt(x + w)}, top {fmt(y)}) lies outside "
                                                          f"the viewBox on node \"{box.id}\"; move the node or set badge.pos to \"left\" or \"center\"")
                for e in edges:  # the pill straddles the top edge of its box: keep it clear of arrows that meet that edge
                    for anchor in getattr(e, which):
                        if anchor.node == box.id and anchor.side == "top" and x - 6 <= anchor_xy(box, "top", anchor.t)[0] <= x + w + 6:
                            message = (f'{label}: the badge pill sits where arrow "{e.id}" meets the top of "{box.id}"; '
                                       f'set badge.pos to another position or move the anchor')
                            if not any(w_.message == message and w_.path == f"flow.steps[{s.id}].badge" for w_ in r.warnings):
                                r.warn(f"flow.steps[{s.id}].badge", message)
    return FlowLayout(width, int(math.ceil(lowest + MARGIN_BOTTOM)), boxes, links)


def entity_height(e: Entity) -> int:
    return ER_HEAD + ER_ROW * len(e.fields) + ER_PAD


def layout_model(r: Report, entities: list, relations: list) -> ModelLayout:
    boxes = {e.id: Box(e.id, e.wide[0], e.wide[1], e.wide[2], entity_height(e)) for e in entities}
    boxes_problems(r, boxes, MODEL_WIDTH, lambda i: f"model.entities[{i}].wide", "data model")
    for e in entities:
        w = boxes[e.id].w
        p = f"model.entities[{e.id}]"
        where = f"data model, box {fmt(w)} wide"
        check_fit(r, f"{p}.name", e.name, ENAME_STYLE, w - 24, where)
        check_fit(r, f"{p}.note", e.note, ENOTE_STYLE, w - 24, where)
        for i, f in enumerate(e.fields):
            check_fit(r, f"{p}.fields[{i + 1}].name", f.name, EFIELD_STYLE, w - 52, where)
    lowest = max([b.bottom for b in boxes.values()] or [0])
    links = []
    for i, rel in enumerate(relations):
        a_from, a_to = rel.wide
        link = connect(anchor_xy(boxes[a_from.node], a_from.side, a_from.t), SIDES[a_from.side],
                       anchor_xy(boxes[a_to.node], a_to.side, a_to.t), SIDES[a_to.side])
        links.append(link)
        where = f"model.relations[{rel.src}->{rel.dst}].wide"
        outside = outside_note(link, MODEL_WIDTH)
        if outside:
            r.error(where, f"data model: the line leaves the viewBox ({outside}); move the anchors or the boxes, or use sides that leave more room")
        warn_crossings(r, where, "data model", link, boxes, (rel.src, rel.dst))
        lowest = max(lowest, max(py for _, py in link.points))
    return ModelLayout(MODEL_WIDTH, int(math.ceil(lowest + MARGIN_BOTTOM)), boxes, links)


# ---------------------------------------------------------------- loading and validating

def read_toml(path: Path, r: Report) -> dict | None:
    try:
        text = path.read_bytes().decode("utf-8-sig")
    except (OSError, UnicodeDecodeError) as exc:
        r.error("", f"cannot read file: {exc}")
        return None
    try:
        return tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        r.error("", f"TOML syntax error: {exc}")
        return None


def flatten_ui(table: dict, prefix: str = "") -> dict:
    """Leaves of ui.toml: pairs {en, de}, month lists {en: [...], de: [...]} and plain values, keyed by dotted path."""
    out: dict[str, object] = {}
    for key, value in table.items():
        path = f"{prefix}.{key}" if prefix else key
        if isinstance(value, dict) and not (set(value) <= set(LANGS) and value):
            out.update(flatten_ui(value, path))
        else:
            out[path] = value
    return out


def load_ui(path: Path) -> tuple[dict | None, Report]:
    r = Report(display_path(path))
    data = read_toml(path, r)
    if data is None:
        return None, r
    flat = flatten_ui(data)
    for key in flat:
        if key not in UI_KEYS:
            r.error(key, f'unknown interface string{suggest(key, UI_KEYS)}')
    for key, kind in UI_KEYS.items():
        if key not in flat:
            r.error(key, "missing interface string" + (" (a pair: .en and .de)" if kind == "pair" else ""))
            continue
        value = flat[key]
        if kind == "str":
            if not isinstance(value, str) or not value.strip():
                r.error(key, "must be a non-empty string")
        elif kind == "pair":
            pair_from(r, value, key)
        else:  # months
            if not isinstance(value, dict):
                r.error(key, "must be a table with en and de lists of twelve month names")
                continue
            for lang in LANGS:
                months = value.get(lang)
                if (not isinstance(months, list) or len(months) != 12
                        or any(not isinstance(m, str) or not m.strip() for m in months)):
                    r.error(f"{key}.{lang}", "must be a list of twelve month names")
    return (None if r.errors else data), r


def tr(ui: dict, key: str, lang: str) -> str:
    node: object = ui
    for part in key.split("."):
        node = node[part]  # type: ignore[index]
    return node[lang]  # type: ignore[index]


def parse_date(r: Report, value: object, path: str) -> datetime.date | None:
    if isinstance(value, datetime.datetime):
        return value.date()
    if isinstance(value, datetime.date):
        return value
    if isinstance(value, str):
        try:
            return datetime.date.fromisoformat(value.strip())
        except ValueError:
            pass
    r.error(path, 'must be a date such as 2026-10-26')
    return None


def parse_anchor_pair(r: Report, parent: dict, key: str, path: str, boxes: dict, what: str) -> tuple | None:
    if key not in parent:
        r.error(path, f'missing required key: two anchors, for example ["a.right", "b.left"]')
        return None
    v = parent[key]
    if not isinstance(v, list) or len(v) != 2:
        r.error(path, 'must be a list of two anchors, for example ["a.right", "b.left"]')
        return None
    a = parse_anchor(r, v[0], f"{path}[1]", boxes, what)
    b = parse_anchor(r, v[1], f"{path}[2]", boxes, what)
    if a and b and a.node == b.node:
        r.error(path, f'both anchors are on "{a.node}"; a connector joins two different {PLURAL[what]}')
        return None
    return (a, b) if a and b else None


def validate_project(data: dict, stem: str, label: str, path: Path) -> tuple[Project | None, Report]:
    r = Report(label)
    check_unknown(r, data, "", {"meta", "hero", "why", "flow", "model", "decisions", "role", "result"})

    # ---- meta
    meta = get_table(r, data, "meta", "meta") or {}
    check_unknown(r, meta, "meta", {"slug", "order", "status", "tech", "demo_url", "og_image", "facts_as_of", "notice"})
    slug = get_str(r, meta, "slug", "meta.slug", regex=SLUG_RE, regex_hint="lower-case letters, digits and single hyphens")
    if slug and slug != stem:
        r.error("meta.slug", f'must equal the file name: expected "{stem}", found "{slug}"')
    order = get_int(r, meta, "order", "meta.order")
    status = get_str(r, meta, "status", "meta.status", choices=list(STATUSES))
    tech: list[str] = []
    for i, item in enumerate(get_list(r, meta, "tech", "meta.tech", minimum=1, maximum=8, what="technology tags")):
        if isinstance(item, str) and clean(item):
            tech.append(clean(item))
        else:
            r.error(f"meta.tech[{i + 1}]", "must be a non-empty string")
    demo_url = get_str(r, meta, "demo_url", "meta.demo_url", required=False)
    if demo_url and not re.match(r"^(https://\S+|/(?!/)\S*)$", demo_url):
        r.error("meta.demo_url", 'must be an https:// address or a site path starting with /')
    og_image = get_str(r, meta, "og_image", "meta.og_image", required=False)
    if og_image and not re.match(r"^(?!/)(?!.*\.\.)[A-Za-z0-9_./-]+$", og_image):
        r.error("meta.og_image", 'must be a path inside the site without a leading slash, for example "assets/img/og-example.png"')
    facts_as_of = parse_date(r, meta["facts_as_of"], "meta.facts_as_of") if "facts_as_of" in meta else None
    if "facts_as_of" not in meta:
        r.error("meta.facts_as_of", "missing required key: a date such as 2026-10-26")
    notice = get_pair(r, meta, "notice", "meta.notice", required=False)

    # ---- hero
    hero_in = get_table(r, data, "hero", "hero") or {}
    check_unknown(r, hero_in, "hero", {"eyebrow", "title", "subtitle", "lead", "stats", "facts"})
    hero: dict = {
        "eyebrow": get_pair(r, hero_in, "eyebrow", "hero.eyebrow"),
        "title": get_pair(r, hero_in, "title", "hero.title"),
        "subtitle": get_pair(r, hero_in, "subtitle", "hero.subtitle"),
        "lead": get_pair(r, hero_in, "lead", "hero.lead", rich=True),
        "stats": [], "facts": [],
    }
    stats_in = get_list(r, hero_in, "stats", "hero.stats", what="stat tiles")
    if "stats" in hero_in and len(stats_in) != 4:
        r.error("hero.stats", f"a page needs exactly 4 stat tiles, found {len(stats_in)}")
    for i, item in enumerate(stats_in):
        p = item_path("hero.stats", i)
        if not isinstance(item, dict):
            r.error(p, "must be a table with value and label")
            continue
        check_unknown(r, item, p, {"value", "label"})
        value = get_pair(r, item, "value", f"{p}.value", plain_ok=True)
        label_pair = get_pair(r, item, "label", f"{p}.label")
        if value and any(len(value[lang]) > 12 for lang in LANGS):
            r.warn(f"{p}.value", "value is longer than 12 characters; the tile shows it in large type, keep it short")
        if value and label_pair:
            hero["stats"].append({"value": value, "label": label_pair})
    for i, item in enumerate(get_list(r, hero_in, "facts", "hero.facts", minimum=1, maximum=6, what="facts")):
        p = item_path("hero.facts", i)
        if not isinstance(item, dict):
            r.error(p, "must be a table with label and value")
            continue
        check_unknown(r, item, p, {"label", "value"})
        label_pair, value = get_pair(r, item, "label", f"{p}.label"), get_pair(r, item, "value", f"{p}.value")
        if label_pair and value:
            hero["facts"].append({"label": label_pair, "value": value})

    # ---- why
    why_in = get_table(r, data, "why", "why") or {}
    check_unknown(r, why_in, "why", {"heading", "paragraphs", "notes"})
    why: dict = {"heading": get_pair(r, why_in, "heading", "why.heading"), "paragraphs": [], "notes": []}
    paragraphs = get_list(r, why_in, "paragraphs", "why.paragraphs", minimum=1, maximum=4, what="paragraphs")
    if paragraphs and not 2 <= len(paragraphs) <= 3:
        r.warn("why.paragraphs", f"the page design shows two or three paragraphs, found {len(paragraphs)}")
    for i, item in enumerate(paragraphs):
        pair = pair_from(r, item, f"why.paragraphs[#{i + 1}]")
        if pair:
            check_rich(r, pair, f"why.paragraphs[#{i + 1}]")
            why["paragraphs"].append(pair)
    why["notes"] = read_notes(r, why_in, "why.notes", 3)
    if why["notes"] and len(why["notes"]) != 2:
        r.warn("why.notes", f"the page design shows two side notes, found {len(why['notes'])}")

    # ---- flow
    flow_errors_before = len(r.errors)
    flow_in = get_table(r, data, "flow", "flow") or {}
    check_unknown(r, flow_in, "flow", {"heading", "description", "nodes", "edges", "steps"})
    flow_heading = get_pair(r, flow_in, "heading", "flow.heading")
    flow_description = get_pair(r, flow_in, "description", "flow.description")
    nodes, node_ids = read_nodes(r, flow_in)
    edges, edge_ids = read_edges(r, flow_in, node_ids)
    steps = read_steps(r, flow_in, node_ids, edge_ids)
    flow_layouts: dict = {}
    if nodes and len(r.errors) == flow_errors_before:
        for which in ("wide", "tall"):
            layout = layout_flow(r, nodes, edges, steps, which)
            if layout:
                flow_layouts[which] = layout
    used_nodes = {i for s in steps for i in s.nodes}
    used_edges = {i for s in steps for i in s.edges}
    for n in nodes:
        if steps and n.id not in used_nodes:
            r.warn(f"flow.nodes[{n.id}]", "node is not used in any step, so it never lights up")
    for e in edges:
        if steps and e.id not in used_edges:
            r.warn(f"flow.edges[{e.id}]", "arrow is not used in any step, so it never lights up")
    if steps and not 4 <= len(steps) <= 6:
        r.warn("flow.steps", f"the page design shows four to six steps, found {len(steps)}")

    # ---- model
    model_errors_before = len(r.errors)
    model_in = get_table(r, data, "model", "model") or {}
    check_unknown(r, model_in, "model", {"heading", "description", "caption", "entities", "relations", "notes"})
    model_heading = get_pair(r, model_in, "heading", "model.heading")
    model_description = get_pair(r, model_in, "description", "model.description")
    model_caption = get_pair(r, model_in, "caption", "model.caption", rich=True)
    entities, entity_ids = read_entities(r, model_in)
    relations = read_relations(r, model_in, entity_ids)
    model_notes = read_notes(r, model_in, "model.notes", 3)
    model_layout = layout_model(r, entities, relations) if entities and len(r.errors) == model_errors_before else None

    # ---- decisions, role, result
    dec_in = get_table(r, data, "decisions", "decisions") or {}
    check_unknown(r, dec_in, "decisions", {"heading", "items"})
    decisions: dict = {"heading": get_pair(r, dec_in, "heading", "decisions.heading", required=False), "items": []}
    items = get_list(r, dec_in, "items", "decisions.items", minimum=1, maximum=6, what="decision cards")
    if items and not 3 <= len(items) <= 4:
        r.warn("decisions.items", f"the page design shows three or four decision cards, found {len(items)}")
    for i, item in enumerate(items):
        p = item_path("decisions.items", i)
        if not isinstance(item, dict):
            r.error(p, "must be a table with title and text")
            continue
        check_unknown(r, item, p, {"title", "text"})
        title, text = get_pair(r, item, "title", f"{p}.title"), get_pair(r, item, "text", f"{p}.text", rich=True)
        if title and text:
            decisions["items"].append({"title": title, "text": text})

    role_in = get_table(r, data, "role", "role") or {}
    check_unknown(r, role_in, "role", {"heading", "bullets"})
    role: dict = {"heading": get_pair(r, role_in, "heading", "role.heading", required=False), "bullets": []}
    bullets = get_list(r, role_in, "bullets", "role.bullets", minimum=1, maximum=8, what="bullets")
    if bullets and not 4 <= len(bullets) <= 6:
        r.warn("role.bullets", f"the page design shows four to six bullets, found {len(bullets)}")
    for i, item in enumerate(bullets):
        pair = pair_from(r, item, f"role.bullets[#{i + 1}]")
        if pair:
            check_rich(r, pair, f"role.bullets[#{i + 1}]")
            role["bullets"].append(pair)

    res_in = get_table(r, data, "result", "result") or {}
    check_unknown(r, res_in, "result", {"heading", "text"})
    result = {"heading": get_pair(r, res_in, "heading", "result.heading"), "text": get_pair(r, res_in, "text", "result.text", rich=True)}

    if r.errors:
        return None, r
    project = Project(
        stem=stem, path=path, slug=slug, order=order, status=status, tech=tech, demo_url=demo_url, og_image=og_image,
        facts_as_of=facts_as_of, notice=notice, hero=hero, why=why, flow_heading=flow_heading,
        flow_description=flow_description, nodes=nodes, edges=edges, steps=steps, model_heading=model_heading,
        model_description=model_description, model_caption=model_caption, entities=entities, relations=relations,
        model_notes=model_notes, decisions=decisions, role=role, result=result,
        flow_layouts=flow_layouts, model_layout=model_layout,
    )
    return project, r


def read_notes(r: Report, parent: dict, path: str, maximum: int) -> list:
    out = []
    for i, item in enumerate(get_list(r, parent, "notes", path, required=False, maximum=maximum, what="notes")):
        p = item_path(path, i)
        if not isinstance(item, dict):
            r.error(p, "must be a table with title and text")
            continue
        check_unknown(r, item, p, {"title", "text"})
        title, text = get_pair(r, item, "title", f"{p}.title"), get_pair(r, item, "text", f"{p}.text", rich=True)
        if title and text:
            out.append({"title": title, "text": text})
    return out


def read_ident(r: Report, item: dict, p_base: str, index: int, seen: dict, what: str) -> str | None:
    ident = get_str(r, item, "id", item_path(p_base, index) + ".id", regex=ID_RE,
                    regex_hint="start with a lower-case letter, then lower-case letters, digits, - or _")
    if ident:
        if ident in seen:
            r.error(item_path(p_base, index, ident) + ".id", f'duplicate {what} id "{ident}"')
            return None
        seen[ident] = True
    return ident


def read_nodes(r: Report, flow_in: dict) -> tuple[list, list]:
    """The valid nodes and every declared node id (a node with another mistake still counts as declared)."""
    nodes: list[Node] = []
    declared: list[str] = []
    seen: dict = {}
    items = get_list(r, flow_in, "nodes", "flow.nodes", minimum=2, what="boxes")
    for i, item in enumerate(items):
        if not isinstance(item, dict):
            r.error(item_path("flow.nodes", i), "must be a table")
            continue
        ident = read_ident(r, item, "flow.nodes", i, seen, "node")
        if ident:
            declared.append(ident)
        p = item_path("flow.nodes", i, ident)
        check_unknown(r, item, p, {"id", "tag", "title", "role", "wide", "tall"})
        tag = get_pair(r, item, "tag", f"{p}.tag", plain_ok=True)
        title, role = get_pair(r, item, "title", f"{p}.title"), get_pair(r, item, "role", f"{p}.role")
        wide, tall = triple(r, item, "wide", f"{p}.wide"), triple(r, item, "tall", f"{p}.tall")
        if ident and tag and title and role and wide and tall:
            nodes.append(Node(ident, tag, title, role, wide, tall))
    return nodes, declared


def read_edges(r: Report, flow_in: dict, node_ids: list) -> tuple[list, list]:
    boxes = dict.fromkeys(node_ids)
    edges: list[Edge] = []
    declared: list[str] = []
    seen: dict = {}
    for i, item in enumerate(get_list(r, flow_in, "edges", "flow.edges", minimum=1, what="arrows")):
        if not isinstance(item, dict):
            r.error(item_path("flow.edges", i), "must be a table")
            continue
        ident = read_ident(r, item, "flow.edges", i, seen, "edge")
        if ident:
            declared.append(ident)
        p = item_path("flow.edges", i, ident)
        check_unknown(r, item, p, {"id", "wide", "tall"})
        wide = parse_anchor_pair(r, item, "wide", f"{p}.wide", boxes, "node")
        tall = parse_anchor_pair(r, item, "tall", f"{p}.tall", boxes, "node")
        if ident and wide and tall:
            edges.append(Edge(ident, wide, tall))
    return edges, declared


def id_list(r: Report, parent: dict, key: str, path: str, known, what: str, minimum: int, required: bool) -> list:
    out: list[str] = []
    for i, ident in enumerate(get_list(r, parent, key, path, required=required, minimum=minimum, what=f"{what} ids")):
        if not isinstance(ident, str):
            r.error(f"{path}[{i + 1}]", "must be a string id")
        elif ident not in known:
            r.error(f"{path}[{i + 1}]", f'unknown {what} "{ident}"{suggest(ident, known)}; known {PLURAL[what]}: {", ".join(known) or "none"}')
        elif ident in out:
            r.error(f"{path}[{i + 1}]", f'{what} "{ident}" is listed twice')
        else:
            out.append(ident)
    return out


def read_steps(r: Report, flow_in: dict, node_ids: list, edge_ids: list) -> list:
    steps: list[Step] = []
    seen: dict = {}
    for i, item in enumerate(get_list(r, flow_in, "steps", "flow.steps", minimum=1, what="steps")):
        if not isinstance(item, dict):
            r.error(item_path("flow.steps", i), "must be a table")
            continue
        ident = read_ident(r, item, "flow.steps", i, seen, "step")
        p = item_path("flow.steps", i, ident)
        check_unknown(r, item, p, {"id", "title", "text", "nodes", "edges", "badge"})
        title = get_pair(r, item, "title", f"{p}.title")
        text = get_pair(r, item, "text", f"{p}.text", rich=True, links=False)
        nodes = id_list(r, item, "nodes", f"{p}.nodes", node_ids, "node", 1, True)
        edges = id_list(r, item, "edges", f"{p}.edges", edge_ids, "edge", 0, False)
        badge = None
        if "badge" in item:
            badge_in = get_table(r, item, "badge", f"{p}.badge")
            if badge_in is not None:
                check_unknown(r, badge_in, f"{p}.badge", {"node", "text", "pos"})
                b_node = get_str(r, badge_in, "node", f"{p}.badge.node")
                if b_node and b_node not in node_ids:
                    r.error(f"{p}.badge.node", f'unknown node "{b_node}"{suggest(b_node, node_ids)}; known nodes: {", ".join(node_ids)}')
                    b_node = None
                elif b_node and b_node not in nodes:
                    r.warn(f"{p}.badge.node", f'the badge sits on "{b_node}", which is dimmed in this step; add it to the step\'s nodes')
                b_text = get_pair(r, badge_in, "text", f"{p}.badge.text", plain_ok=True)
                pos = get_str(r, badge_in, "pos", f"{p}.badge.pos", required=False, choices=["left", "center", "right"]) or "right"
                if b_node and b_text:
                    badge = Badge(b_node, {lang: b_text[lang].upper() for lang in LANGS}, pos)  # shown in capitals, like the tags
        if ident and title and text:
            steps.append(Step(ident, title, text, nodes, edges, badge))
    return steps


def read_entities(r: Report, model_in: dict) -> tuple[list, list]:
    entities: list[Entity] = []
    declared: list[str] = []
    seen: dict = {}
    for i, item in enumerate(get_list(r, model_in, "entities", "model.entities", minimum=2, what="entities")):
        if not isinstance(item, dict):
            r.error(item_path("model.entities", i), "must be a table")
            continue
        ident = read_ident(r, item, "model.entities", i, seen, "entity")
        if ident:
            declared.append(ident)
        p = item_path("model.entities", i, ident)
        check_unknown(r, item, p, {"id", "kind", "name", "note", "wide", "fields"})
        kind = get_str(r, item, "kind", f"{p}.kind", choices=list(KINDS))
        name, note = get_pair(r, item, "name", f"{p}.name"), get_pair(r, item, "note", f"{p}.note")
        wide = triple(r, item, "wide", f"{p}.wide")
        fields: list[Field] = []
        raw_fields = get_list(r, item, "fields", f"{p}.fields", minimum=1, maximum=MAX_FIELDS, what="fields")
        for j, f in enumerate(raw_fields):
            fp = f"{p}.fields[{j + 1}]"
            if not isinstance(f, dict):
                r.error(fp, 'must be a table such as { key = "PK", name.en = "...", name.de = "..." }')
                continue
            check_unknown(r, f, fp, {"key", "name"})
            key = ""
            if "key" in f:
                key = get_str(r, f, "key", f"{fp}.key", choices=["PK", "FK"]) or ""
            fname = get_pair(r, f, "name", f"{fp}.name")
            if fname:
                fields.append(Field(key, fname))
        if ident and kind and name and note and wide and fields and len(fields) == len(raw_fields):
            entities.append(Entity(ident, kind, name, note, wide, fields))
    return entities, declared


def read_relations(r: Report, model_in: dict, entity_ids: list) -> list:
    relations: list[Relation] = []
    boxes = dict.fromkeys(entity_ids)
    for i, item in enumerate(get_list(r, model_in, "relations", "model.relations", minimum=1, what="relations")):
        p = f"model.relations[#{i + 1}]"
        if not isinstance(item, dict):
            r.error(p, "must be a table")
            continue
        check_unknown(r, item, p, {"from", "to", "cardinality", "wide", "text"})
        ends = []
        for key in ("from", "to"):
            ident = get_str(r, item, key, f"{p}.{key}")
            if ident and ident not in entity_ids:
                r.error(f"{p}.{key}", f'unknown entity "{ident}"{suggest(ident, entity_ids)}; known entities: {", ".join(entity_ids) or "none"}')
                ident = None
            ends.append(ident)
        if ends[0] and ends[0] == ends[1]:
            r.error(p, f'"from" and "to" are both "{ends[0]}"; a relation joins two different entities')
        card = get_str(r, item, "cardinality", f"{p}.cardinality", choices=list(CARDINALITIES))
        wide = parse_anchor_pair(r, item, "wide", f"{p}.wide", boxes, "entity")
        if wide and ends[0] and ends[1] and (wide[0].node != ends[0] or wide[1].node != ends[1]):
            r.error(f"{p}.wide", f'anchors must start on "{ends[0]}" and end on "{ends[1]}" (the "from" and "to" entities)')
            wide = None
        text = get_pair(r, item, "text", f"{p}.text")
        if ends[0] and ends[1] and ends[0] != ends[1] and card and wide and text:
            relations.append(Relation(ends[0], ends[1], card, wide, text))
    return relations


def lenient_neighbour(path: Path) -> dict | None:
    """Only meta.order, meta.slug and hero.title of another content file, read without validating the rest."""
    try:
        data = tomllib.loads(path.read_bytes().decode("utf-8-sig"))
        meta, hero = data.get("meta", {}), data.get("hero", {})
        order, slug = meta.get("order"), meta.get("slug")
        if isinstance(order, bool) or not isinstance(order, int) or not isinstance(slug, str) or not slug.strip():
            return None
        title = hero.get("title") if isinstance(hero, dict) else None
        texts = {}
        if isinstance(title, dict):
            for lang in LANGS:
                value = title.get(lang)
                if isinstance(value, str) and clean(value):
                    texts[lang] = clean(value)
        fallback = texts.get("en") or texts.get("de") or slug.strip()
        return {"order": order, "slug": slug.strip(), "title": {lang: texts.get(lang, fallback) for lang in LANGS},
                "title_ok": len(texts) == 2, "file": path.name}
    except Exception:
        return None


