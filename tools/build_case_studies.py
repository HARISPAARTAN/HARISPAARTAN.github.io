# ---------------------------------------------------------------- the build

@dataclass
class Build:
    outputs: dict = field(default_factory=dict)   # Path -> text
    errors: list = field(default_factory=list)
    warnings: list = field(default_factory=list)
    complete: bool = True                          # False when only some pages were produced (--only)


def content_files(content_dir: Path) -> list[Path]:
    return sorted(p for p in content_dir.glob("*.toml") if p.name != "ui.toml")


def build(content_dir: Path, ui_path: Path, out_dir: Path, only: str | None = None) -> Build:
    """Validate the content and render the pages in memory. Nothing is written here."""
    result = Build()
    ui, ui_report = load_ui(ui_path)
    result.errors += ui_report.errors
    result.warnings += ui_report.warnings
    files = content_files(content_dir)
    if not files:
        result.errors.append(Issue(display_path(content_dir), "", "no content files found (expected <slug>.toml)"))
        return result
    if ui is None:
        return result
    if only is not None:
        return build_only(content_dir, files, ui, out_dir, only, result)
    return build_all(files, ui, out_dir, result)


def output_path(out_dir: Path, slug: str, lang: str) -> Path:
    return out_dir / slug / "de" / "index.html" if lang == "de" else out_dir / slug / "index.html"


def load_project(path: Path, site_root: Path | None = None) -> tuple[Project | None, Report]:
    label = display_path(path)
    r = Report(label)
    data = read_toml(path, r)
    if data is None:
        return None, r
    project, report = validate_project(data, path.stem, label, path)
    if project and project.og_image and site_root is not None and (site_root / "assets").is_dir():
        if not (site_root / project.og_image).is_file():
            report.warn("meta.og_image", f'file "{project.og_image}" does not exist in the site')
    return project, report


def build_all(files: list[Path], ui: dict, out_dir: Path, result: Build) -> Build:
    projects: list[Project] = []
    for path in files:
        project, report = load_project(path, out_dir.parent)
        result.errors += report.errors
        result.warnings += report.warnings
        if project:
            projects.append(project)
    if result.errors:
        return result
    projects.sort(key=lambda p: (p.order, p.slug))
    orders = [p.order for p in projects]
    if orders != list(range(1, len(projects) + 1)):
        detail = ", ".join(f"{p.slug}={p.order}" for p in projects)
        result.errors.append(Issue(display_path(files[0].parent), "meta.order",
                                   f"the orders of all content files must be exactly 1..{len(projects)} without gaps or duplicates; found {detail}"))
        return result
    total = len(projects)
    for i, p in enumerate(projects):
        prev = Neighbour(projects[i - 1].slug, projects[i - 1].hero["title"]) if i > 0 else None
        nxt = Neighbour(projects[i + 1].slug, projects[i + 1].hero["title"]) if i < total - 1 else None
        for lang in LANGS:
            result.outputs[output_path(out_dir, p.slug, lang)] = render_case_study(p, ui, lang, total, prev, nxt)
    result.outputs[out_dir / "index.html"] = render_list_page(projects, ui)
    return result


def build_only(content_dir: Path, files: list[Path], ui: dict, out_dir: Path, slug: str, result: Build) -> Build:
    result.complete = False
    target = content_dir / f"{slug}.toml"
    if target not in files:
        result.errors.append(Issue(display_path(target), "", f'no content file for slug "{slug}" (found: {", ".join(f.stem for f in files)})'))
        return result
    project, report = load_project(target, out_dir.parent)
    result.errors += report.errors
    result.warnings += report.warnings
    if not project:
        return result
    others = [info for f in files if f != target and (info := lenient_neighbour(f)) is not None]
    orders_seen = [project.order] + [o["order"] for o in others]
    total = max(len(files), max(orders_seen))
    by_order: dict[int, dict] = {}
    for info in others:
        if info["order"] in by_order or info["order"] == project.order:
            result.warnings.append(Issue(display_path(content_dir / info["file"]), "meta.order",
                                         f'order {info["order"]} is also claimed by another content file; the pager uses the first one'))
            continue
        by_order[info["order"]] = info

    def pick(order: int, direction: str) -> Neighbour | None:
        info = by_order.get(order)
        if info is None:
            result.warnings.append(Issue(display_path(target), "pager",
                                         f'no readable content file with meta.order = {order}; the "{direction}" link falls back to the home page work section'))
            return None
        if not info["title_ok"]:
            result.warnings.append(Issue(display_path(content_dir / info["file"]), "hero.title",
                                         "title is missing or incomplete; the pager shows what it can read"))
        if info["slug"] != Path(info["file"]).stem:
            result.warnings.append(Issue(display_path(content_dir / info["file"]), "meta.slug",
                                         f'slug "{info["slug"]}" differs from the file name; the pager link uses the slug'))
        return Neighbour(info["slug"], info["title"])

    prev = pick(project.order - 1, "previous") if project.order > 1 else None
    nxt = pick(project.order + 1, "next") if project.order < total else None
    for lang in LANGS:
        result.outputs[output_path(out_dir, project.slug, lang)] = render_case_study(project, ui, lang, total, prev, nxt)
    return result


# ---------------------------------------------------------------- writing and checking

def stale_pages(out_dir: Path, outputs: dict) -> list[Path]:
    """Generated pages under out_dir that no content file produces any more."""
    stale = []
    if out_dir.is_dir():
        for path in sorted(list(out_dir.glob("*/index.html")) + list(out_dir.glob("*/de/index.html"))):
            if path in outputs:
                continue
            try:
                head = path.read_bytes()[:400].decode("utf-8", "replace")
            except OSError:
                continue
            if GENERATED_MARK in head:
                stale.append(path)
    return stale


def write_outputs(outputs: dict, out_dir: Path, remove_stale: bool, say) -> tuple[int, int, int]:
    """Write the pages that changed. Returns (written, unchanged, removed)."""
    written = unchanged = removed = 0
    for path in sorted(outputs):
        data = outputs[path].encode("utf-8")
        shown = display_path(path)
        if path.exists() and path.read_bytes() == data:
            unchanged += 1
            say(f"unchanged  {shown}")
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        written += 1
        say(f"wrote      {shown}")
    if remove_stale:
        for path in stale_pages(out_dir, outputs):
            path.unlink()
            removed += 1
            say(f"removed    {display_path(path)} (no content file any more)")
            for folder in (path.parent, path.parent.parent):
                if folder != out_dir and folder.is_dir() and not any(folder.iterdir()):
                    folder.rmdir()
    return written, unchanged, removed


def check_outputs(outputs: dict, out_dir: Path, complete: bool) -> list[str]:
    problems = []
    for path in sorted(outputs):
        shown = display_path(path)
        if not path.exists():
            problems.append(f"{shown}: missing (run: python tools/build_case_studies.py)")
            continue
        old = path.read_bytes().decode("utf-8", "replace").replace("\r\n", "\n").split("\n")
        new = outputs[path].split("\n")
        if path.read_bytes() != outputs[path].encode("utf-8"):
            diff = next((i for i, (a, b) in enumerate(zip(old, new)) if a != b), min(len(old), len(new)))
            why = "line endings differ (expected LF)" if old == new else f"differs from the content files, first at line {diff + 1}"
            problems.append(f"{shown}: {why} (run: python tools/build_case_studies.py)")
    if complete:
        for path in stale_pages(out_dir, outputs):
            problems.append(f"{display_path(path)}: stale page, no content file produces it any more (run: python tools/build_case_studies.py)")
    return problems


def main(argv: list[str] | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    parser = argparse.ArgumentParser(
        prog="build_case_studies.py", description="Build the bilingual case-study pages.",
        epilog="The content format is described in content/case-studies/SCHEMA.md.")
    parser.add_argument("--check", action="store_true", help="build in memory; exit 1 if the pages on disk differ or the content is invalid")
    parser.add_argument("--only", metavar="SLUG", help="validate one content file and write only its two pages")
    parser.add_argument("--content-dir", type=Path, default=DEFAULT_CONTENT_DIR, help="folder with <slug>.toml files (default: content/case-studies)")
    parser.add_argument("--ui", type=Path, default=None, help="interface strings (default: <content-dir>/ui.toml)")
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR, help="output folder (default: work)")
    args = parser.parse_args(argv)
    content_dir = args.content_dir.resolve()
    ui_path = (args.ui or content_dir / "ui.toml").resolve()
    out_dir = args.out_dir.resolve()

    result = build(content_dir, ui_path, out_dir, args.only)
    for issue in result.warnings:
        print(f"warning: {issue}", file=sys.stderr)
    if result.errors:
        for issue in result.errors:
            print(f"error: {issue}", file=sys.stderr)
        print(f"{len(result.errors)} error(s); nothing was written." if not args.check else f"{len(result.errors)} error(s).", file=sys.stderr)
        return 1
    if args.check:
        problems = check_outputs(result.outputs, out_dir, result.complete)
        if problems:
            for line in problems:
                print(f"drift: {line}", file=sys.stderr)
            print(f"{len(problems)} page(s) out of date.", file=sys.stderr)
            return 1
        print(f"OK: {len(result.outputs)} page(s) are current.")
        return 0
    written, unchanged, removed = write_outputs(result.outputs, out_dir, remove_stale=result.complete, say=print)
    extra = f", {removed} removed" if removed else ""
    print(f"Built {len(result.outputs)} page(s): {written} written, {unchanged} unchanged{extra}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
